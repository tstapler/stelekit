#!/usr/bin/env python3
"""Generate ChromeTableFixture.kt from the chrome-table block of ux.md (plan Task 3.6.4c).

  gen-chrome-fixture.py --ux <ux.md> --out <ChromeTableFixture.kt> [--check]
  gen-chrome-fixture.py --selftest

The generator is the only code that reads ux.md; tests parse the generated constant.
"""
import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
DEFAULT_UX = REPO / "project_plans/excalidraw-sketch-engine/design/ux.md"
DEFAULT_OUT = REPO / "kmp/src/commonTest/kotlin/dev/stapler/stelekit/sketch/v2/ChromeTableFixture.kt"
REGEN_CMD = "python3 scripts/sketch-chrome/gen-chrome-fixture.py"

BLOCK = re.compile(r"<!-- chrome-table:start -->\n```text\n(.*?)\n```\n", re.S)


def extract_block(ux_text: str) -> str:
    matches = BLOCK.findall(ux_text)
    if len(matches) != 1:
        raise SystemExit(f"expected exactly one chrome-table block in ux.md, found {len(matches)}")
    return matches[0]


def fnv1a64(text: str) -> str:
    h = 0xCBF29CE484222325
    for b in text.encode("utf-8"):
        h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return f"{h:016x}"


DOLLAR = "${'$'}"
QUOTE3 = "${'\"'}${'\"'}${'\"'}"


def kotlin_escape(text: str) -> str:
    return text.replace("$", DOLLAR).replace('"""', QUOTE3)


def kotlin_unescape(text: str) -> str:
    return text.replace(QUOTE3, '"""').replace(DOLLAR, "$")


def render(block: str) -> str:
    return (
        "package dev.stapler.stelekit.sketch.v2\n\n"
        "// GENERATED by scripts/sketch-chrome/gen-chrome-fixture.py from the chrome-table block of\n"
        "// project_plans/excalidraw-sketch-engine/design/ux.md. Do not edit; regenerate with:\n"
        f"//   {REGEN_CMD}\n"
        "object ChromeTableFixture {\n"
        f'    const val CONTENT_HASH: String = "{fnv1a64(block)}"\n\n'
        f'    val TABLE: String = """{kotlin_escape(block)}"""\n'
        "}\n"
    )


def decode(kotlin_source: str) -> str:
    m = re.search(r'val TABLE: String = """(.*)"""\n}\n$', kotlin_source, re.S)
    if not m:
        raise SystemExit("generated file has no TABLE constant")
    return kotlin_unescape(m.group(1))


def selftest() -> int:
    tricky = "[params]\nprice = ${'x'} $5 \"\"\" quote\nlabel | Zurück | 日本語 | ü\n"
    ux = f"<!-- chrome-table:start -->\n```text\n{tricky}```\n"
    block = extract_block(ux)
    if block != tricky.rstrip("\n"):
        print("selftest: extraction differs", file=sys.stderr)
        return 1
    out = render(block)
    if decode(out) != block:
        print("selftest: decoded constant differs from the block", file=sys.stderr)
        return 1
    body = out.split('val TABLE: String = """', 1)[1].rsplit('"""\n}', 1)[0]
    leftover = body.replace(DOLLAR, "").replace(QUOTE3, "")
    if '"""' in leftover or "$" in leftover:
        print("selftest: an unescaped $ or triple quote survived", file=sys.stderr)
        return 1
    print("selftest ok")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--ux", type=Path, default=DEFAULT_UX)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()
    if args.selftest:
        return selftest()
    expected = render(extract_block(args.ux.read_text(encoding="utf-8")))
    if args.check:
        actual = args.out.read_text(encoding="utf-8") if args.out.exists() else None
        if actual != expected:
            print(f"{args.out} differs from the chrome-table block of {args.ux}.\n"
                  f"Regenerate with: {REGEN_CMD} --ux {args.ux} --out {args.out}", file=sys.stderr)
            return 1
        print("chrome fixture up to date")
        return 0
    args.out.write_text(expected, encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
