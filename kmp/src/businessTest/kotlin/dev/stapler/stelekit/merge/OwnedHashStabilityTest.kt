package dev.stapler.stelekit.merge

import arrow.core.Either
import dev.stapler.stelekit.merge.ActiveTargetWriterContractTest.ActiveHarness
import kotlinx.coroutines.runBlocking
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/** A re-save by the app with no user edit must not read as a user edit (no false EditedByUser). */
class OwnedHashStabilityTest {
    private val key = PageKey("Sketch Digest")

    private fun owned(vararg lines: String): MergePage {
        val body = lines.mapIndexed { i, l -> MergeBlock("owned-${i + 1}", l) }
        val marker = mapOf(OwnedMarker.OWNED to "true", OwnedMarker.DIGEST to "demo", OwnedMarker.HASH to OwnedHash.ofBody(body))
        return MergePage(key.name, blocks = listOf(MergeBlock("owned-0", "Generated by SteleKit. Edits are overwritten.", properties = marker)) + body)
    }

    @Test
    fun aNoOpResaveLeavesTheHashAndTheNextReplaceUnchanged() = runBlocking<Unit> {
        val h = ActiveHarness()
        try {
            val page = owned("alpha", "beta")
            h.writer.replaceOwnedPage(key, page, null)
            val written = OwnedHash.of(h.snapshot(key)!!)
            h.editContent(key, "beta", "beta") // actor update plus GraphWriter.savePage re-render
            assertEquals(written, OwnedHash.of(h.snapshot(key)!!))
            assertEquals(OwnedHash.of(page), written)
            val result = h.writer.replaceOwnedPage(key, page, written)
            assertTrue(result is Either.Right && result.value == WriteOutcome.Unchanged, "$result")
        } finally {
            h.close()
        }
    }
}
