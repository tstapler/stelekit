package dev.stapler.stelekit.merge

import arrow.core.Either
import dev.stapler.stelekit.error.DomainError
import kotlinx.coroutines.runBlocking
import kotlin.test.AfterTest
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertIs
import kotlin.test.assertNotNull
import kotlin.test.assertNull
import kotlin.test.assertTrue

/** What an [OwnedPageWriterContractSuite] needs from the writer under test. Synthetic data only. */
interface OwnedHarness {
    val writer: OwnedPageWriter

    /** Writes [text] as the page file and imports it the way a restart would. */
    suspend fun seed(key: PageKey, text: String)

    /** Writes [text] to the page file only; the DB does not know it (a file that appeared after we looked). */
    suspend fun seedFileOnly(key: PageKey, text: String)

    /** A user edit of one block. */
    suspend fun editContent(key: PageKey, from: String, to: String)

    fun fileText(key: PageKey): String?

    /** Block data as stored, or null with no page. */
    suspend fun snapshot(key: PageKey): MergePage?

    suspend fun close()
}

/** Block-data contract of [OwnedPageWriter], separate from [TargetWriterContractSuite] so no fake changes. */
abstract class OwnedPageWriterContractSuite {
    protected abstract fun newHarness(): OwnedHarness

    private val opened = mutableListOf<OwnedHarness>()
    protected fun harness(): OwnedHarness = newHarness().also { opened += it }

    @AfterTest
    fun closeHarnesses() {
        runBlocking { opened.forEach { it.close() } }
        opened.clear()
    }

    protected val key = PageKey("Sketch Digest")
    private val markerText = "Generated by SteleKit. Edits are overwritten."

    protected fun owned(vararg lines: String, slug: String = "demo"): MergePage {
        val body = lines.mapIndexed { i, l -> MergeBlock("owned-${i + 1}", l) }
        val marker = mapOf(OwnedMarker.OWNED to "true", OwnedMarker.DIGEST to slug, OwnedMarker.HASH to OwnedHash.ofBody(body))
        return MergePage(key.name, blocks = listOf(MergeBlock("owned-0", markerText, properties = marker)) + body)
    }

    private fun <T> Either<DomainError, T>.ok(): T = fold({ error("expected Right but was $it") }, { it })

    protected fun Either<DomainError, *>.refusal(): WriteRefusedReason =
        assertIs<DomainError.MergeError.WriteRefused>((this as Either.Left).value).reason

    private fun hashOf(page: MergePage) = OwnedHash.of(page)

    @Test
    fun createWritesTheMarkerFirstBlockAndBody() = runBlocking<Unit> {
        val h = harness()
        assertIs<WriteOutcome.Created>(h.writer.replaceOwnedPage(key, owned("alpha", "beta"), null).ok())
        val stored = assertNotNull(h.snapshot(key))
        assertEquals(listOf(markerText, "alpha", "beta"), stored.blocks.map { it.content })
        assertEquals("true", stored.blocks.first().properties[OwnedMarker.OWNED])
        assertEquals(hashOf(owned("alpha", "beta")), hashOf(stored))
    }

    @Test
    fun replaceUnchangedWritesNothing() = runBlocking<Unit> {
        val h = harness()
        h.writer.replaceOwnedPage(key, owned("alpha", "beta"), null).ok()
        val before = h.fileText(key)
        val result = h.writer.replaceOwnedPage(key, owned("alpha", "beta"), hashOf(owned("alpha", "beta"))).ok()
        assertEquals(WriteOutcome.Unchanged, result)
        assertEquals(before, h.fileText(key))
    }

    @Test
    fun replaceChangedSwapsTheBodyAndFreshHash() = runBlocking<Unit> {
        val h = harness()
        h.writer.replaceOwnedPage(key, owned("alpha", "beta"), null).ok()
        val next = owned("gamma", "delta", "epsilon")
        assertIs<WriteOutcome.Updated>(h.writer.replaceOwnedPage(key, next, hashOf(owned("alpha", "beta"))).ok())
        val stored = assertNotNull(h.snapshot(key))
        assertEquals(listOf(markerText, "gamma", "delta", "epsilon"), stored.blocks.map { it.content })
        assertEquals(hashOf(next), stored.blocks.first().properties[OwnedMarker.HASH])
        assertEquals(WriteOutcome.Unchanged, h.writer.replaceOwnedPage(key, next, hashOf(next)).ok())
    }

    @Test
    fun editedByUserIsRefusedAndNothingIsWritten() = runBlocking<Unit> {
        val h = harness()
        h.writer.replaceOwnedPage(key, owned("alpha", "beta"), null).ok()
        h.editContent(key, "beta", "beta by hand")
        val before = h.fileText(key)
        val result = h.writer.replaceOwnedPage(key, owned("gamma"), hashOf(owned("alpha", "beta")))
        assertIs<WriteRefusedReason.EditedByUser>(result.refusal())
        assertEquals(before, h.fileText(key))
    }

    @Test
    fun aStaleExpectedPriorHashIsEditedByUser() = runBlocking<Unit> {
        val h = harness()
        h.writer.replaceOwnedPage(key, owned("alpha"), null).ok()
        assertIs<WriteRefusedReason.EditedByUser>(h.writer.replaceOwnedPage(key, owned("gamma"), "not-the-hash").refusal())
    }

    @Test
    fun aPageWithoutTheMarkerIsNotOwnedAndUntouched() = runBlocking<Unit> {
        val h = harness()
        h.seed(key, "- my own notes\n- more notes\n")
        val before = h.fileText(key)
        assertIs<WriteRefusedReason.NotOwned>(h.writer.replaceOwnedPage(key, owned("alpha"), null).refusal())
        assertEquals(before, h.fileText(key))
    }

    @Test
    fun aPagePropertyOnlyMarkerIsNotRecognised() = runBlocking<Unit> {
        val h = harness()
        h.seed(key, "stelekit-owned:: true\nstelekit-digest:: demo\nstelekit-digest-hash:: x\n- alpha\n")
        assertIs<WriteRefusedReason.NotOwned>(h.writer.replaceOwnedPage(key, owned("alpha"), null).refusal())
    }

    @Test
    fun aFileThatAppearedAfterTheCallerSawNoPageIsNotOwned() = runBlocking<Unit> {
        val h = harness()
        h.seedFileOnly(key, "- written by someone else\n")
        assertIs<WriteRefusedReason.NotOwned>(h.writer.replaceOwnedPage(key, owned("alpha"), null).refusal())
        assertEquals("- written by someone else\n", h.fileText(key))
    }

    @Test
    fun conflictMarkersInTheFileAreConflicted() = runBlocking<Unit> {
        val h = harness()
        h.writer.replaceOwnedPage(key, owned("alpha"), null).ok()
        val clean = checkNotNull(h.fileText(key))
        val conflicted = "<<<<<<< HEAD\n$clean=======\n- other device\n>>>>>>> origin/main\n"
        h.seedFileOnly(key, conflicted)
        assertIs<WriteRefusedReason.Conflicted>(h.writer.replaceOwnedPage(key, owned("gamma"), hashOf(owned("alpha"))).refusal())
        assertEquals(conflicted, h.fileText(key))
    }

    @Test
    fun anotherDigestsPageIsNotOwned() = runBlocking<Unit> {
        val h = harness()
        h.writer.replaceOwnedPage(key, owned("alpha", slug = "one"), null).ok()
        assertIs<WriteRefusedReason.NotOwned>(h.writer.replaceOwnedPage(key, owned("gamma", slug = "two"), null).refusal())
    }

    @Test
    fun contentWithoutAMatchingMarkerIsRefusedBeforeAnyWrite() = runBlocking<Unit> {
        val h = harness()
        val bad = owned("alpha").let { it.copy(blocks = it.blocks.mapIndexed { i, b -> if (i == 0) b.copy(properties = b.properties + (OwnedMarker.HASH to "stale")) else b }) }
        assertIs<WriteRefusedReason.NotRoundTrippable>(h.writer.replaceOwnedPage(key, bad, null).refusal())
        assertNull(h.fileText(key))
        assertTrue(h.snapshot(key) == null)
    }
}
