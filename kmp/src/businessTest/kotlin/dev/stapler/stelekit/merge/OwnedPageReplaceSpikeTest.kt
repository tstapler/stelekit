/**
 * Story 5.1 spike (project_plans/home-project-sketching, ADR-006): what an owned-page replace costs on
 * [ActiveTargetWriter]. CHARACTERIZATION tests: they pin today's behaviour and stay green; Story 5.4b
 * flips writeRefusesToReplaceAnExistingBlock and replaceComposedFromPublicPrimitivesWorksButLeavesAnEmptyWindow.
 * Synthetic data only. Findings: ADR-006 amendment.
 */
class OwnedPageReplaceSpikeTest {
    private val harnesses = mutableListOf<ActiveHarness>()
    private fun harness() = ActiveHarness().also { harnesses += it }

    @AfterTest
    fun close() {
        runBlocking { harnesses.forEach { it.close() } }
        harnesses.clear()
    }

    private val key = PageKey("Sketch Digest")
    private val marker = mapOf("stelekit-owned" to "true", "stelekit-digest" to "demo", "stelekit-digest-hash" to "h0")
    private val markerText = "Generated by SteleKit. Edits are overwritten."
    private fun body(vararg lines: String) = lines.mapIndexed { i, l -> MergeBlock("owned-${i + 1}", l) }

    /** Marker as page properties: bare `key:: value` lines on top, as `LogseqPageSerializer` renders `Page.properties`. */
    private fun propertyForm(vararg lines: String) = MergePage(key.name, properties = marker, blocks = body(*lines))

    /** Marker as the properties of a visible first block. */
    private fun blockForm(vararg lines: String, props: Map<String, String> = marker) =
        MergePage(key.name, blocks = listOf(MergeBlock("owned-0", markerText, properties = props)) + body(*lines))

    /** Candidate OwnedHash: sha256 over the body blocks (everything after the marker block), uuid-free and `id`-free. */
    private fun canonical(b: MergeBlock): String = buildString {
        append('[').append(b.content)
        b.properties.filterKeys { it != "id" }.entries.sortedBy { it.key }.forEach { (k, v) -> append('|').append(k).append('=').append(v) }
        b.children.forEach { append(canonical(it)) }
        append(']')
    }
    private fun ownedHash(blocks: List<MergeBlock>) = blocks.joinToString("") { canonical(it) }.encodeUtf8().sha256().hex()
    private fun isMarker(b: MergeBlock) = b.properties["stelekit-owned"] == "true"
    private fun bodyOf(page: MergePage): List<MergeBlock> = page.blocks.dropWhile(::isMarker)

    /** What a fresh loader makes of the file text, as another device or a restart would see it. */
    private data class Reloaded(val page: Page, val blocks: List<Block>) {
        val contents get() = blocks.sortedBy { it.position }.map { it.content }
        fun asMerge() = MergeConverters.toMergePage(page, blocks)
    }

    private suspend fun ActiveHarness.reload(k: PageKey = key): Reloaded {
        val p2 = InMemoryPageRepository()
        val b2 = InMemoryBlockRepository()
        val scope = CoroutineScope(SupervisorJob() + Dispatchers.Default)
        val actor2 = DatabaseWriteActor(b2, p2, scope = scope)
        try {
            val path = "/graphs/active/pages/${k.name}.md"
            GraphLoader(fs, p2, b2, externalWriteActor = actor2)
                .applyExternalFileChange(FilePath(path), checkNotNull(fs.readFile(path)), ParseMode.FULL, DatabaseWriteActor.Priority.HIGH)
            val page = checkNotNull(p2.getPageByName(k.name).first().fold({ null }, { it }))
            return Reloaded(page, b2.getBlocksForPage(page.uuid).first().fold({ emptyList() }, { it }))
        } finally {
            actor2.close()
            scope.cancel()
        }
    }

    private suspend fun ActiveHarness.read(): MergePage = checkNotNull(writer.readExisting(key).fold({ error("$it") }, { it }))

    // (b)(i) where the marker lives ---------------------------------------------------------------

    @Test
    fun pagePropertyMarkerIsDemotedToBodyBlocksOnReload() = runBlocking<Unit> {
        val h = harness()
        assertIs<WriteOutcome.Created>(h.writer.write(key, propertyForm("alpha", "beta")).fold({ error("$it") }, { it }))
        println("SPIKE property-form file:\n${h.fileText(key)}---")

        // The live DB (the writer saved the row with the properties) still has them as page properties ...
        assertEquals(marker, h.read().properties)
        assertEquals(listOf("alpha", "beta"), h.read().blocks.map { it.content })

        // ... but a fresh loader (restart, other device, sync pull) reads the bare lines as blocks.
        val reloaded = h.reload()
        println("SPIKE property-form reload props=${reloaded.page.properties} blocks=${reloaded.contents}")
        assertEquals(emptyMap(), reloaded.page.properties)
        assertEquals(listOf("stelekit-owned:: true", "stelekit-digest:: demo", "stelekit-digest-hash:: h0", "alpha", "beta"), reloaded.contents)
    }

    @Test
    fun onlyAnEmptyBulletWithPropertiesIsReadBackAsPageProperties() = runBlocking<Unit> {
        val forms = linkedMapOf(
            "bare" to ("stelekit-owned:: true\nstelekit-digest:: demo\n- alpha\n" to false),
            "emptyBulletTab" to ("-\n\tstelekit-owned:: true\n\tstelekit-digest:: demo\n- alpha\n" to true),
            "emptyBullet2sp" to ("-\n  stelekit-owned:: true\n  stelekit-digest:: demo\n- alpha\n" to true),
            "bulletWithProp" to ("- stelekit-owned:: true\n\tstelekit-digest:: demo\n- alpha\n" to false),
        )
        for ((name, spec) in forms) {
            val h = harness()
            val k = PageKey("Form $name")
            h.seed(k, spec.first)
            val r = h.reload(k)
            println("SPIKE form=$name props=${r.page.properties} blocks=${r.contents}")
            assertEquals(spec.second, r.page.properties["stelekit-owned"] == "true", name)
        }
    }

    @Test
    fun activeWriterCannotProduceTheEmptyBulletForm() = runBlocking<Unit> {
        val h = harness()
        val result = h.writer.write(key, MergePage(key.name, blocks = listOf(MergeBlock(null, "", properties = marker)) + body("alpha")))
        val err = assertIs<DomainError.MergeError.WriteRefused>((result as Either.Left).value)
        println("SPIKE empty-first-block refusal: ${err.reason.message}")
        assertIs<NotRoundTrippable.InsertedContentChanged>((err.reason as WriteRefusedReason.NotRoundTrippable).detail)
        assertNull(h.fileText(key))
    }

    @Test
    fun markerOnAVisibleFirstBlockSurvivesWriteReloadAndResave() = runBlocking<Unit> {
        val h = harness()
        assertIs<WriteOutcome.Created>(h.writer.write(key, blockForm("alpha", "beta")).fold({ error("$it") }, { it }))
        val text = checkNotNull(h.fileText(key))
        println("SPIKE block-form file:\n$text---")

        assertEquals(marker, h.read().blocks.first().properties.filterKeys { it != "id" })
        val reloaded = h.reload()
        assertEquals(emptyMap(), reloaded.page.properties, "not absorbed into page properties: the first block is not empty")
        assertEquals(marker, reloaded.asMerge().blocks.first().properties.filterKeys { it != "id" })

        h.editContent(key, "beta", "beta") // no-op edit: actor update plus GraphWriter.savePage re-render
        assertEquals(text, h.fileText(key), "re-save of an untouched owned page is byte-stable on the active writer")
    }

    // (b)(ii) hash stability ----------------------------------------------------------------------

    @Test
    fun canonicalBodyHashIsStableAcrossWriteReloadResaveInBlockForm() = runBlocking<Unit> {
        val h = harness()
        h.writer.write(key, blockForm("alpha", "beta"))
        val written = ownedHash(bodyOf(h.read()))
        val reloaded = ownedHash(bodyOf(h.reload().asMerge()))
        h.editContent(key, "beta", "beta")
        val resaved = ownedHash(bodyOf(h.read()))
        val withUuids = bodyOf(h.read()).map(BlockContentHash::of) == bodyOf(h.reload().asMerge()).map(BlockContentHash::of)
        println("SPIKE hash write=$written reload=$reloaded resave=$resaved uuidBearingEqualAcrossReload=$withUuids")
        assertEquals(written, reloaded)
        assertEquals(written, resaved)
        assertTrue(withUuids, "explicit id:: makes uuid-bearing hashes stable too; the uuid-free form is still preferred")
    }

    @Test
    fun hashOverTheWholePageIsNotStableInPropertyFormBecauseReloadAddsMarkerBlocks() = runBlocking<Unit> {
        val h = harness()
        h.writer.write(key, propertyForm("alpha", "beta"))
        val live = ownedHash(h.read().blocks)
        val reloaded = ownedHash(h.reload().asMerge().blocks)
        println("SPIKE property-form hash live=$live reload=$reloaded")
        assertNotEquals(live, reloaded, "a page-wide hash would flag a false EditedByUser after the first reload")
    }

    @Test
    fun aUserEditChangesTheCanonicalHash() = runBlocking<Unit> {
        val h = harness()
        h.writer.write(key, blockForm("alpha", "beta"))
        val before = ownedHash(bodyOf(h.read()))
        h.editContent(key, "beta", "beta edited")
        assertNotEquals(before, ownedHash(bodyOf(h.read())))
    }

    // (a) + (b)(iii) the replace path -------------------------------------------------------------

    @Test
    fun writeRefusesToReplaceAnExistingBlock() = runBlocking<Unit> {
        val h = harness()
        h.writer.write(key, blockForm("alpha", "beta"))
        val before = h.fileText(key)

        val replace = h.writer.write(key, blockForm("alpha CHANGED", "beta"))

        val err = assertIs<DomainError.MergeError.WriteRefused>((replace as Either.Left).value)
        assertIs<NotRoundTrippable.ExistingContentChanged>((err.reason as WriteRefusedReason.NotRoundTrippable).detail)
        assertEquals(before, h.fileText(key), "refusal writes nothing")
    }

    @Test
    fun replaceComposedFromPublicPrimitivesWorksButLeavesAnEmptyWindow() = runBlocking<Unit> {
        val h = harness()
        h.writer.write(key, blockForm("alpha", "beta"))
        val old = h.read().blocks
        val removed = h.writer.removeBlocks(
            key,
            old.mapNotNull { it.uuid }.toSet(),
            old.associate { it.uuid!! to BlockContentHash.of(it) },
        ).fold({ error("$it") }, { it })
        assertEquals(old.size, removed.removed.size)
        println("SPIKE after removeBlocks: file=${h.fileText(key)?.length} chars, blocks=${h.read().blocks.size}")
        assertEquals(emptyList(), h.read().blocks, "between the two calls the page exists with no marker and no body")

        val written = h.writer.write(key, blockForm("gamma", "delta", props = marker + ("stelekit-digest-hash" to "h1"))).fold({ error("$it") }, { it })
        println("SPIKE re-insert outcome=$written")
        assertIs<WriteOutcome.Updated>(written)
        assertEquals(listOf(markerText, "gamma", "delta"), h.read().blocks.map { it.content })
        assertEquals("h1", h.read().blocks.first().properties["stelekit-digest-hash"])
        assertEquals("h1", h.reload().asMerge().blocks.first().properties["stelekit-digest-hash"])
    }

    @Test
    fun pageBeingEditedIsRetryableOnTheRemovePath() = runBlocking<Unit> {
        val h = harness()
        h.writer.write(key, blockForm("alpha", "beta"))
        h.editInEditor(key, "beta", "typing...")
        val old = h.read().blocks

        val result = h.writer.removeBlocks(key, old.mapNotNull { it.uuid }.toSet(), old.associate { it.uuid!! to BlockContentHash.of(it) })

        val err = assertIs<DomainError.MergeError.Retryable>((result as Either.Left).value)
        assertEquals(WriteRetryReason.PageBeingEdited.message, err.message)
        h.flushEditor(key)
    }

    // (b)(iv) raw file write ----------------------------------------------------------------------

    @Test
    fun graphWriterOffersNoRawPageWrite() {
        val names = GraphWriter::class.java.methods.map { it.name.substringBefore('-') }.toSet()
        println("SPIKE GraphWriter page entry points: ${names.filter { "age" in it || "rite" in it }.sorted()}")
        assertTrue("savePage" in names && "deletePage" in names)
        assertFalse(names.any { it.contains("raw", true) || it.contains("bytes", true) })
    }

    // (c) conflict markers ------------------------------------------------------------------------

    @Test
    fun aConflictedFileIsNotImportedSoOnlyTheFileRevealsTheConflict() = runBlocking<Unit> {
        val h = harness()
        h.writer.write(key, blockForm("alpha", "beta"))
        val clean = checkNotNull(h.fileText(key))
        val conflicted = "<<<<<<< HEAD\n$clean=======\n- $markerText\n\tstelekit-owned:: true\n- other device\n>>>>>>> origin/main\n"
        assertTrue(ConflictMarkerDetector.hasConflictMarkers(conflicted))

        h.seed(key, conflicted) // writes the file, then runs the live loader's import path

        assertEquals(listOf(markerText, "alpha", "beta"), h.read().blocks.map { it.content }, "the DB keeps the pre-conflict digest")
        assertTrue(ConflictMarkerDetector.hasConflictMarkers(checkNotNull(h.fileText(key))), "the file carries the markers")
    }
}
