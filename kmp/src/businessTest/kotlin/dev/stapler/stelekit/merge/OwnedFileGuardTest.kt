package dev.stapler.stelekit.merge

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertIs
import kotlin.test.assertNotEquals

class OwnedFileGuardTest {
    private fun owned(vararg lines: String, slug: String = "demo", text: String = "Generated by SteleKit."): MergePage {
        val body = lines.map { MergeBlock(null, it) }
        val marker = mapOf(OwnedMarker.OWNED to "true", OwnedMarker.DIGEST to slug, OwnedMarker.HASH to OwnedHash.ofBody(body))
        return MergePage("P", blocks = listOf(MergeBlock(null, text, properties = marker)) + body)
    }

    private fun decide(existing: MergePage?, incoming: MergePage, expected: String? = null, file: String? = "x") =
        OwnedFileGuard.decide("P", file, existing, incoming, expected)

    private fun refusal(d: OwnedFileGuard.Decision) = assertIs<OwnedFileGuard.Decision.Refuse>(d).reason

    @Test
    fun noExistingPageIsCreate() = assertEquals(OwnedFileGuard.Decision.Create, decide(null, owned("a"), file = null))

    @Test
    fun matchingHashWithNewBodyIsReplaceAndSameBodyIsUnchanged() {
        val old = owned("a")
        assertEquals(OwnedFileGuard.Decision.Replace, decide(old, owned("b"), OwnedHash.of(old)))
        assertEquals(OwnedFileGuard.Decision.Unchanged, decide(old, owned("a"), OwnedHash.of(old)))
    }

    @Test
    fun aChangedMarkerTextIsReplaceEvenWithTheSameBody() {
        assertEquals(OwnedFileGuard.Decision.Replace, decide(owned("a"), owned("a", text = "New banner")))
    }

    @Test
    fun conflictMarkersWinOverEverythingElse() {
        val file = "<<<<<<< HEAD\n- a\n=======\n- b\n>>>>>>> x\n"
        assertIs<WriteRefusedReason.Conflicted>(refusal(decide(null, owned("a"), file = file)))
        assertIs<WriteRefusedReason.Conflicted>(refusal(decide(owned("a"), owned("b"), file = file)))
    }

    @Test
    fun missingMarkerIsNotOwnedAndAPropertyOnlyMarkerIsNotRecognised() {
        val plain = MergePage("P", blocks = listOf(MergeBlock(null, "hello")))
        assertIs<WriteRefusedReason.NotOwned>(refusal(decide(plain, owned("a"))))
        val propertyOnly = MergePage("P", properties = mapOf(OwnedMarker.OWNED to "true"), blocks = listOf(MergeBlock(null, "hello")))
        assertIs<WriteRefusedReason.NotOwned>(refusal(decide(propertyOnly, owned("a"))))
    }

    @Test
    fun aBodyThatNoLongerMatchesTheMarkerIsEditedByUser() {
        val old = owned("a")
        val edited = old.copy(blocks = old.blocks.mapIndexed { i, b -> if (i == 1) b.copy(content = "a!") else b })
        assertIs<WriteRefusedReason.EditedByUser>(refusal(decide(edited, owned("b"))))
        assertIs<WriteRefusedReason.EditedByUser>(refusal(decide(old, owned("b"), expected = "other")))
    }

    @Test
    fun incomingWithoutAFreshMatchingHashOrVisibleMarkerTextIsRefused() {
        val stale = owned("a").let { it.copy(blocks = listOf(it.blocks[0].copy(properties = it.blocks[0].properties + (OwnedMarker.HASH to "stale"))) + it.blocks.drop(1)) }
        assertIs<WriteRefusedReason.NotRoundTrippable>(refusal(decide(null, stale, file = null)))
        assertIs<WriteRefusedReason.NotRoundTrippable>(refusal(decide(null, owned("a", text = " "), file = null)))
        assertIs<WriteRefusedReason.NotRoundTrippable>(refusal(decide(null, MergePage("P", blocks = listOf(MergeBlock(null, "x"))), file = null)))
    }

    @Test
    fun hashIsUuidAndIdFreeAndExcludesTheMarkerBlock() {
        val a = MergePage("P", blocks = listOf(MergeBlock("u0", "m"), MergeBlock("u1", "x", properties = mapOf("id" to "u1", "k" to "v"))))
        val b = MergePage("P", blocks = listOf(MergeBlock("z0", "other banner"), MergeBlock("z1", "x", properties = mapOf("k" to "v"))))
        assertEquals(OwnedHash.of(a), OwnedHash.of(b))
        assertNotEquals(OwnedHash.of(a), OwnedHash.of(a.copy(blocks = a.blocks.dropLast(1) + MergeBlock("u1", "y"))))
    }
}
