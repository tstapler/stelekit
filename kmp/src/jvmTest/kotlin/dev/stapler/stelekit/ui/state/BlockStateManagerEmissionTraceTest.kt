// jvmTest-reason: real SQLDelight driver (in-memory SQLite), no compose.ui.test import
package dev.stapler.stelekit.ui.state

import dev.stapler.stelekit.table.TableSheetRealFeedHarness
import kotlinx.coroutines.runBlocking
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.joinAll
import java.io.File
import kotlin.test.Test
import kotlin.test.assertTrue

/**
 * Records (does not assert on) the order in which the real manager and SQLDelight feed emit for
 * the hard table-commit interleavings, and regenerates implementation/emission-trace.md.
 */
class BlockStateManagerEmissionTraceTest {
    private val s0 = "| a | b |\n|---|---|\n| 1 | 2 |"
    private val s1 = "| a | b |\n|---|---|\n| 1 | 3 |"
    private val s2 = "| a | b |\n|---|---|\n| 1 | 4 |"
    private val foreign = "| a | b |\n|---|---|\n| 9 | 9 |"
    private val labels = mapOf(s0 to "S0", s1 to "S1", s2 to "S2", foreign to "F")
    private fun label(c: String?) = if (c == null) "null" else labels[c] ?: "other(${c.length})"

    private val out = StringBuilder()

    private class Scenario(val h: TableSheetRealFeedHarness, val out: StringBuilder) {
        var seen = 0
        var step = 0
        private fun flushLog() {
            val all = h.orderedLog
            for (e in all.drop(seen)) out.appendLine("    - $e")
            seen = all.size
        }
        fun note(text: String) { out.appendLine("- step ${++step}: $text"); flushLog() }
        fun after(text: String) {
            out.appendLine("- step ${++step}: $text")
            flushLog()
            out.appendLine("    - manager content: ${h.labelOf(h.managerContent())}")
        }
        fun commit(label: String, content: String): kotlinx.coroutines.Job {
            h.event("issue commit $label")
            val j = h.manager.updateBlockContent(h.blockUuid, content, 0, restoreEditFocus = false)
            j.invokeOnCompletion { h.event("JOB completed: commit $label") }
            return j
        }
        fun undo(expected: String): kotlinx.coroutines.Job {
            h.event("issue undo (expect $expected)")
            return h.manager.undo().also { j -> j.invokeOnCompletion { h.event("JOB completed: undo") } }
        }
        fun redo(expected: String): kotlinx.coroutines.Job {
            h.event("issue redo (expect $expected)")
            return h.manager.redo().also { j -> j.invokeOnCompletion { h.event("JOB completed: redo") } }
        }
    }

    private fun scenario(title: String, body: suspend Scenario.(TableSheetRealFeedHarness) -> Unit): Int {
        out.appendLine("### $title\n")
        val h = TableSheetRealFeedHarness(s0)
        h.labelOf = ::label
        var count = 0
        runBlocking {
            h.start(s0)
            val sc = Scenario(h, out)
            sc.after("initial load (S0 displayed; initial subscription emission)")
            sc.body(h)
            h.settle()
            sc.after("settled (no emission for 400 ms)")
            count = h.emissions.size
        }
        h.close()
        out.appendLine()
        return count
    }

    @Test
    fun recordEmissionTrace() {
        out.appendLine("# Emission trace (generated)\n")
        out.appendLine("Generated by `BlockStateManagerEmissionTraceTest` (jvmTest) over `TableSheetRealFeedHarness`: real `BlockStateManager` (write actor, invalidation and push sources wired as in `GraphContentViewModelSetup`) over SQLDelight on in-memory SQLite. Labels: S0 = loaded content, S1/S2 = sheet commits (`restoreEditFocus = false`), F = foreign write. Each step lists, in one arrival-ordered log, the `EMISSION` lines (`getBlockByUuid` for the block) interleaved with `issue` and `JOB completed` markers; `dbVersion` is a side column and never a decision input. Timing is real (Dispatchers.Default), so order within a run is what was observed, not a guarantee.\n")
        val counts = mutableListOf<Int>()

        counts += scenario("(a) two quick commits S1, S2 (issued back to back, no wait between)") { h ->
            val j1 = commit("S1", s1)
            note("issue commit S1 (lower bound 0), no wait")
            val j2 = commit("S2", s2)
            note("issue commit S2 (lower bound 0), no wait")
            joinAll(j1, j2)
            after("both commit Jobs completed")
            h.settle()
            after("settled after Jobs")
        }

        counts += scenario("(a2) two sequential commits S1, S2 (each joins its predecessor, as TableCommitter does)") { h ->
            commit("S1", s1).join()
            commit("S2", s2).join()
            after("both Jobs joined, no settle between")
        }

        counts += scenario("(b) commit S1, undo, immediate re-commit S1 (S1 acked before undo)") { h ->
            commit("S1", s1).join()
            h.settle()
            after("commit S1 done and settled (S1 Acked)")
            undo("S0").join()
            note("undo Job joined (expected S0)")
            commit("S1", s1).join()
            after("immediate re-commit S1 (no settle after undo) Job joined")
        }

        counts += scenario("(b2) commit S1, undo, immediate re-commit S1 (no settle before undo)") { h ->
            commit("S1", s1).join()
            note("commit S1 Job joined, no settle")
            undo("S0").join()
            note("undo Job joined (expected S0)")
            commit("S1", s1).join()
            after("immediate re-commit S1 Job joined")
        }

        counts += scenario("(c) commit S1, undo, redo") { h ->
            commit("S1", s1).join()
            after("commit S1 Job joined")
            h.settle(); after("settled")
            undo("S0").join()
            after("undo Job joined (expected S0)")
            h.settle(); after("settled")
            redo("S1").join()
            after("redo Job joined (expected S1)")
        }

        counts += scenario("(c2) Tab, Tab, Ctrl+Z: commit S1, commit S2, undo with no settle") { h ->
            commit("S1", s1).join()
            note("commit S1 Job joined")
            commit("S2", s2).join()
            note("commit S2 Job joined")
            undo("S1").join()
            after("undo Job joined (expected S1)")
        }

        counts += scenario("(d) foreign write F by another writer (via the write actor) after commit S1") { h ->
            commit("S1", s1).join()
            h.settle(); after("commit S1 done and settled")
            h.event("issue foreign write F")
            h.actor.updateBlockContentOnly(h.blockUuid, foreign, h.pageUuid)
            after("foreign write F awaited (actor.updateBlockContentOnly)")
        }

        counts += scenario("(d3) foreign write F, 3 s later, then a sheet commit of S1 (equal to the manager's stale content)") { h ->
            commit("S1", s1).join()
            h.settle(); after("commit S1 done and settled")
            h.event("issue foreign write F")
            h.actor.updateBlockContentOnly(h.blockUuid, foreign, h.pageUuid)
            kotlinx.coroutines.delay(3000)
            after("3 s after foreign write F")
            commit("S1", s1).join()
            h.settle()
            after("sheet re-commits S1 (manager believes S1 is current)")
            val dbRow = h.blockRepo.getBlockByUuid(h.blockUuid).first().getOrNull()?.content
            note("read back DB row: ${label(dbRow)}")
        }

        counts += scenario("(d2) foreign write F straight to the repository (bypasses actor, no invalidation)") { h ->
            h.event("issue foreign write F")
            h.blockRepo.updateBlockContentOnly(h.blockUuid, foreign)
            after("foreign write F awaited (repository direct)")
        }

        File(System.getProperty("user.dir")).let { start ->
            var dir: File? = start
            while (dir != null && !File(dir, "project_plans").isDirectory) dir = dir.parentFile
            val target = File(dir ?: start, "project_plans/table-sheet-editor/implementation/emission-trace.md")
            target.parentFile?.mkdirs()
            target.writeText(out.toString())
        }
        println(out)
        assertTrue(counts.all { it >= 1 }, "every scenario must produce at least one emission: $counts")
    }
}
