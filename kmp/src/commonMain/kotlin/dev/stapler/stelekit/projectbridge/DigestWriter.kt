package dev.stapler.stelekit.projectbridge

import arrow.core.Either
import arrow.core.left
import dev.stapler.stelekit.error.DomainError
import dev.stapler.stelekit.merge.MergeBlock
import dev.stapler.stelekit.merge.MergePage
import dev.stapler.stelekit.merge.OwnedHash
import dev.stapler.stelekit.merge.OwnedMarker
import dev.stapler.stelekit.merge.PageKey
import dev.stapler.stelekit.merge.TargetWriterRouter
import dev.stapler.stelekit.merge.UuidRemap
import dev.stapler.stelekit.merge.WriteOutcome
import dev.stapler.stelekit.merge.WriteRefusedReason
import dev.stapler.stelekit.model.GraphId
import kotlinx.coroutines.CancellationException

/** What one digest write did; [note] is the text shown in the jobs list. */
sealed interface DigestWriteResult {
    val note: String

    data class Written(val created: Boolean) : DigestWriteResult {
        override val note = if (created) "digest page created" else "digest page updated"
    }

    data object Unchanged : DigestWriteResult {
        override val note = "digest page is up to date"
    }

    /** Transient (graph switching, page being edited): retried on the next trigger. */
    data class Deferred(override val note: String) : DigestWriteResult

    /** The page is not ours to replace any more; nothing was written. */
    data class Refused(override val note: String) : DigestWriteResult

    data object Unavailable : DigestWriteResult {
        override val note = PostSyncProjectJob.UNAVAILABLE
    }

    data class Failed(override val note: String) : DigestWriteResult
}

/**
 * Writes the fused digest as an app-owned page (Story 5.4c, ADR-006). The marker-and-hash check and the
 * replace run inside one router `withWriter` block (`OwnedPageWriter`); this class only builds the page and
 * classifies the outcome. It never touches markdown itself.
 */
class DigestWriter(
    private val replace: suspend (GraphId, PageKey, MergePage) -> Either<DomainError, WriteOutcome>,
    private val readBack: suspend (GraphId, PageKey) -> Either<DomainError, MergePage?>,
    private val hasWriter: () -> Boolean,
) {
    constructor(routerProvider: () -> TargetWriterRouter?) : this(
        replace = { target, key, page ->
            routerProvider()?.replaceOwnedPage(target, key, page, null) ?: DomainError.MergeError.Retryable(NO_ROUTER).left()
        },
        readBack = { target, key ->
            routerProvider()?.withWriter(target) { it.readExisting(key) } ?: DomainError.MergeError.Retryable(NO_ROUTER).left()
        },
        hasWriter = { routerProvider() != null },
    )

    suspend fun write(graphId: String, title: String, input: DigestInput): DigestWriteResult {
        if (!hasWriter()) return DigestWriteResult.Unavailable
        val target = GraphId(graphId)
        val key = PageKey(title)
        val page = buildPage(graphId, title, input)
        return try {
            val outcome = replace(target, key, page)
            val result = classify(outcome)
            if (result is DigestWriteResult.Written && !readBackMatches(target, key, page)) {
                DigestWriteResult.Failed("digest page did not read back as written")
            } else {
                result
            }
        } catch (e: CancellationException) {
            throw e
        } catch (e: Throwable) {
            DigestWriteResult.Failed("digest write failed (${e::class.simpleName ?: "Error"})")
        }
    }

    private suspend fun readBackMatches(target: GraphId, key: PageKey, expected: MergePage): Boolean {
        val stored = readBack(target, key).getOrNull() ?: return false
        return OwnedHash.of(stored) == OwnedHash.of(expected) && OwnedMarker.of(stored) != null
    }

    companion object {
        const val MARKER_TEXT = "Generated by SteleKit from your project sketches. Edits to this page are not kept; it is rewritten when the project changes."
        private const val NO_ROUTER = "graph switching; the digest will be written after the next sync"
        private val BULLET = Regex("^- ")

        /**
         * Block 0 is the marker (visible text, owned flag, slug, body hash); blocks 1..n are the digest's
         * top-level lines. The block uuid (written as `id::` by the active writer) derives from (graph, slug, index), so a re-render of equal content
         * is byte-stable and `OwnedHash` ignores them.
         */
        fun buildPage(graphId: String, title: String, input: DigestInput): MergePage {
            val source = GraphId(graphId)
            fun uuid(index: Int) = UuidRemap.uuidFor(source, "digest:${input.slug}:$index")
            fun block(index: Int, content: String) = MergeBlock(uuid(index), content)
            val body = DigestRenderer.renderBlocks(input).mapIndexed { i, line -> block(i + 1, line.replace(BULLET, "")) }
            val marker = MergeBlock(
                uuid(0), MARKER_TEXT,
                linkedMapOf(
                    OwnedMarker.OWNED to "true",
                    OwnedMarker.DIGEST to input.slug,
                    OwnedMarker.HASH to OwnedHash.ofBody(body),
                ),
            )
            return MergePage(title, blocks = listOf(marker) + body)
        }

        internal fun classify(outcome: Either<DomainError, WriteOutcome>): DigestWriteResult = outcome.fold(
            { error ->
                when (error) {
                    is DomainError.MergeError.Retryable -> DigestWriteResult.Deferred(error.message)
                    is DomainError.MergeError.WriteRefused -> DigestWriteResult.Refused(refusalNote(error.reason))
                    else -> DigestWriteResult.Failed("digest write failed")
                }
            },
            { done ->
                when (done) {
                    is WriteOutcome.Created -> DigestWriteResult.Written(created = true)
                    is WriteOutcome.Updated -> DigestWriteResult.Written(created = false)
                    WriteOutcome.Unchanged -> DigestWriteResult.Unchanged
                }
            },
        )

        private fun refusalNote(reason: WriteRefusedReason): String = when (reason) {
            is WriteRefusedReason.Conflicted -> "resolve the sync conflict on the digest page"
            is WriteRefusedReason.EditedByUser -> "digest page was edited; delete or rename it to let the app rewrite it"
            is WriteRefusedReason.NotOwned -> "a page with the digest title already exists and is not app-generated"
            else -> "digest page not written: ${reason.message}"
        }
    }
}
