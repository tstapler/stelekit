package dev.stapler.stelekit.ui.annotate

/**
 * A 5x7 bitmap font for the text inside exported label pills. Compose's common `Canvas` has no text
 * drawing and the platform canvases differ, so the glyphs are painted as filled cells: identical on
 * every target, wasm-safe, and unit-testable without a renderer.
 *
 * Each glyph is five columns, bit 0 = top row. Lowercase maps to uppercase; characters outside the
 * table draw as a hollow box so a label never silently loses text.
 */
object ExportLabelFont {
    const val GLYPH_COLUMNS = 5
    const val GLYPH_ROWS = 7

    /** Columns per character cell including the one-column gap after each glyph. */
    const val ADVANCE_COLUMNS = GLYPH_COLUMNS + 1

    private const val FIRST_CHAR = 0x20
    private const val DEGREE_SIGN = '°'
    private const val SUPERSCRIPT_TWO = '²'
    private const val SUPERSCRIPT_THREE = '³'

    private val MISSING = intArrayOf(0x7F, 0x41, 0x41, 0x41, 0x7F)
    private val DEGREE = intArrayOf(0x00, 0x06, 0x09, 0x09, 0x06)

    // ASCII 0x20..0x60 (space to backtick); lowercase letters reuse the uppercase rows.
    private val TABLE: List<IntArray> = listOf(
        intArrayOf(0x00, 0x00, 0x00, 0x00, 0x00), intArrayOf(0x00, 0x00, 0x5F, 0x00, 0x00),
        intArrayOf(0x00, 0x07, 0x00, 0x07, 0x00), intArrayOf(0x14, 0x7F, 0x14, 0x7F, 0x14),
        intArrayOf(0x24, 0x2A, 0x7F, 0x2A, 0x12), intArrayOf(0x23, 0x13, 0x08, 0x64, 0x62),
        intArrayOf(0x36, 0x49, 0x56, 0x20, 0x50), intArrayOf(0x00, 0x05, 0x03, 0x00, 0x00),
        intArrayOf(0x00, 0x1C, 0x22, 0x41, 0x00), intArrayOf(0x00, 0x41, 0x22, 0x1C, 0x00),
        intArrayOf(0x14, 0x08, 0x3E, 0x08, 0x14), intArrayOf(0x08, 0x08, 0x3E, 0x08, 0x08),
        intArrayOf(0x00, 0x50, 0x30, 0x00, 0x00), intArrayOf(0x08, 0x08, 0x08, 0x08, 0x08),
        intArrayOf(0x00, 0x60, 0x60, 0x00, 0x00), intArrayOf(0x20, 0x10, 0x08, 0x04, 0x02),
        intArrayOf(0x3E, 0x51, 0x49, 0x45, 0x3E), intArrayOf(0x00, 0x42, 0x7F, 0x40, 0x00),
        intArrayOf(0x42, 0x61, 0x51, 0x49, 0x46), intArrayOf(0x21, 0x41, 0x45, 0x4B, 0x31),
        intArrayOf(0x18, 0x14, 0x12, 0x7F, 0x10), intArrayOf(0x27, 0x45, 0x45, 0x45, 0x39),
        intArrayOf(0x3C, 0x4A, 0x49, 0x49, 0x30), intArrayOf(0x01, 0x71, 0x09, 0x05, 0x03),
        intArrayOf(0x36, 0x49, 0x49, 0x49, 0x36), intArrayOf(0x06, 0x49, 0x49, 0x29, 0x1E),
        intArrayOf(0x00, 0x36, 0x36, 0x00, 0x00), intArrayOf(0x00, 0x56, 0x36, 0x00, 0x00),
        intArrayOf(0x08, 0x14, 0x22, 0x41, 0x00), intArrayOf(0x14, 0x14, 0x14, 0x14, 0x14),
        intArrayOf(0x00, 0x41, 0x22, 0x14, 0x08), intArrayOf(0x02, 0x01, 0x51, 0x09, 0x06),
        intArrayOf(0x32, 0x49, 0x79, 0x41, 0x3E), intArrayOf(0x7E, 0x11, 0x11, 0x11, 0x7E),
        intArrayOf(0x7F, 0x49, 0x49, 0x49, 0x36), intArrayOf(0x3E, 0x41, 0x41, 0x41, 0x22),
        intArrayOf(0x7F, 0x41, 0x41, 0x22, 0x1C), intArrayOf(0x7F, 0x49, 0x49, 0x49, 0x41),
        intArrayOf(0x7F, 0x09, 0x09, 0x09, 0x01), intArrayOf(0x3E, 0x41, 0x49, 0x49, 0x7A),
        intArrayOf(0x7F, 0x08, 0x08, 0x08, 0x7F), intArrayOf(0x00, 0x41, 0x7F, 0x41, 0x00),
        intArrayOf(0x20, 0x40, 0x41, 0x3F, 0x01), intArrayOf(0x7F, 0x08, 0x14, 0x22, 0x41),
        intArrayOf(0x7F, 0x40, 0x40, 0x40, 0x40), intArrayOf(0x7F, 0x02, 0x0C, 0x02, 0x7F),
        intArrayOf(0x7F, 0x04, 0x08, 0x10, 0x7F), intArrayOf(0x3E, 0x41, 0x41, 0x41, 0x3E),
        intArrayOf(0x7F, 0x09, 0x09, 0x09, 0x06), intArrayOf(0x3E, 0x41, 0x51, 0x21, 0x5E),
        intArrayOf(0x7F, 0x09, 0x19, 0x29, 0x46), intArrayOf(0x46, 0x49, 0x49, 0x49, 0x31),
        intArrayOf(0x01, 0x01, 0x7F, 0x01, 0x01), intArrayOf(0x3F, 0x40, 0x40, 0x40, 0x3F),
        intArrayOf(0x1F, 0x20, 0x40, 0x20, 0x1F), intArrayOf(0x3F, 0x40, 0x38, 0x40, 0x3F),
        intArrayOf(0x63, 0x14, 0x08, 0x14, 0x63), intArrayOf(0x07, 0x08, 0x70, 0x08, 0x07),
        intArrayOf(0x61, 0x51, 0x49, 0x45, 0x43), intArrayOf(0x00, 0x7F, 0x41, 0x41, 0x00),
        intArrayOf(0x02, 0x04, 0x08, 0x10, 0x20), intArrayOf(0x00, 0x41, 0x41, 0x7F, 0x00),
        intArrayOf(0x04, 0x02, 0x01, 0x02, 0x04), intArrayOf(0x40, 0x40, 0x40, 0x40, 0x40),
        intArrayOf(0x00, 0x01, 0x02, 0x04, 0x00),
    )

    /** The five column bitmasks for [c] (bit 0 = top row). */
    fun glyph(c: Char): IntArray {
        val ch = when (c) {
            SUPERSCRIPT_TWO -> '2'
            SUPERSCRIPT_THREE -> '3'
            else -> c.uppercaseChar()
        }
        if (ch == DEGREE_SIGN) return DEGREE
        val index = ch.code - FIRST_CHAR
        return if (index in TABLE.indices) TABLE[index] else MISSING
    }

    /** Width in pixels of [text] when each font cell is [cell] px; the trailing gap is excluded. */
    fun textWidth(text: String, cell: Float): Float =
        if (text.isEmpty()) 0f else (text.length * ADVANCE_COLUMNS - 1) * cell

    /** Height in pixels of one line of text with cells of [cell] px. */
    fun textHeight(cell: Float): Float = GLYPH_ROWS * cell

    /**
     * Reports every lit cell of [text] as a rectangle: [fill] receives left, top, right, bottom in
     * pixels, with the text starting at ([left], [top]). Vertical runs in a column are merged.
     */
    fun layout(text: String, left: Float, top: Float, cell: Float, fill: (Float, Float, Float, Float) -> Unit) {
        text.forEachIndexed { i, c ->
            val glyph = glyph(c)
            val x = left + i * ADVANCE_COLUMNS * cell
            glyph.forEachIndexed { col, bits ->
                var row = 0
                while (row < GLYPH_ROWS) {
                    if (bits and (1 shl row) == 0) {
                        row++
                        continue
                    }
                    val start = row
                    while (row < GLYPH_ROWS && bits and (1 shl row) != 0) row++
                    fill(x + col * cell, top + start * cell, x + (col + 1) * cell, top + row * cell)
                }
            }
        }
    }
}
